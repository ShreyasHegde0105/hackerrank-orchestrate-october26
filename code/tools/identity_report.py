"""Resolve every request and write code/docs/identity_report.md.

Usage (from the repository root):  python code/tools/identity_report.py
"""
from __future__ import annotations

import sys
from collections import Counter, defaultdict
from pathlib import Path

CODE_DIR = Path(__file__).resolve().parents[1]
if str(CODE_DIR) not in sys.path:
    sys.path.insert(0, str(CODE_DIR))

from audit.identity import IdentityIndex, ResolutionStatus  # noqa: E402
from audit.loader import format_timestamp, load_dataset  # noqa: E402
from audit.models import IdentifierKind, Provenance  # noqa: E402

OUT_PATH = CODE_DIR / "docs" / "identity_report.md"


def section_for(requests_file: str, lines: list[str]) -> None:
    dataset = load_dataset(requests_file=requests_file)
    index = IdentityIndex.from_dataset(dataset)
    results = [(r, index.resolve_request(r)) for r in dataset.requests]
    statuses = Counter(res.status.value for _, res in results)
    methods = Counter(res.method for _, res in results if res.method)
    case_only = sum(1 for r, res in results
                    if res.subject and r.email != r.email.strip().lower())
    with_history = sum(1 for _, res in results if res.subject and res.subject.historical_claims)
    lines += [
        f"## `{requests_file}` ({len(results)} requests)", "",
        f"- Status: {dict(statuses)}",
        f"- Matched via: {dict(methods)}",
        f"- Request emails that match only after case/whitespace normalisation: {case_only}",
        f"- Resolved subjects with historical identifiers to search: {with_history}",
        "",
    ]
    unresolved = [(r, res) for r, res in results if res.status is not ResolutionStatus.RESOLVED]
    lines.append("Ambiguous, unresolved or invalid requests: "
                 + ("none." if not unresolved else ""))
    for r, res in unresolved:
        lines.append(f"- `{r.case_id}` `{r.email}`: {res.status.value}; candidates "
                     f"{sorted({c.user_id for c in res.candidates})}; {'; '.join(res.notes)}")
    lines.append("")
    historical = [(r, res) for r, res in results if res.method == "historical_email"]
    if historical:
        shown = "all" if len(historical) <= 10 else f"first 10 of {len(historical)}"
        lines += [f"Historical-email resolutions ({shown}):", "",
                  "| case_id | request email | user_id | replaced by audit | replaced at |",
                  "|---|---|---|---|---|"]
        for r, res in historical[:10]:
            claim = next(c.claim for c in res.candidates if c.method == "historical_email")
            lines.append(f"| {r.case_id} | `{r.email}` | {res.user_id} | {claim.source} | "
                         f"{format_timestamp(claim.valid_to)} |")
        lines.append("")


def main() -> int:
    dataset = load_dataset()
    index = IdentityIndex.from_dataset(dataset)
    lines = ["# Identity resolution report", "",
             "Generated by `python code/tools/identity_report.py`. Names are never used "
             "for matching; see `audit/identity.py` for the matching priority.", ""]
    for requests_file in ("deletion_requests.csv", "sample_deletion_requests.csv"):
        section_for(requests_file, lines)

    kinds = Counter((c.kind.value, c.provenance.value)
                    for s in index.subjects.values() for c in s.claims)
    lines += ["## Identifier index", "",
              f"{len(index.subjects)} users; claims by kind and provenance: "
              + ", ".join(f"{k}/{p}={n}" for (k, p), n in sorted(kinds.items())), ""]
    lines.append(f"Integrity issues (shared identifiers, broken audit chains, email/hash "
                 f"mismatches, unknown users): {len(index.issues) or 'none'}.")
    for issue in index.issues:
        lines.append(f"- {issue.category}: {issue.detail}")
    lines.append("")

    namesakes = defaultdict(list)
    for user in dataset.users.values():
        namesakes[user.name].append(user.user_id)
    lines += ["## People sharing a name (why names are never matched)", ""]
    lines += [f"- {name}: {', '.join(ids)}" for name, ids in sorted(namesakes.items())
              if len(ids) > 1]
    lines.append("")

    lines += ["## Data-catalog resource links (`LINK_RESOURCE_IDENTITY`)", "",
              "| activity | time | system | resource | label | user | exclusive | trusted |",
              "|---|---|---|---|---|---|---|---|"]
    for l in index.links:
        lines.append(f"| {l.activity_id} | {format_timestamp(l.event_time)} | {l.system_id} | "
                     f"{l.resource_id} | {l.label} | {l.user_id} | {l.exclusive} | "
                     f"{l.trusted}{' (' + l.note + ')' if l.note else ''} |")
    lines.append("")

    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {OUT_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
